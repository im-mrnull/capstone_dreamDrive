def _ci(c: list, d: int = 2) -> str:
    return f"[{c[0]:.{d}f}, {c[1]:.{d}f}]"


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def bootstrap_rows() -> list[str]:
    b = _load(BOOT_PATH)
    if b is None:
        return [f"*pending — run `python scripts/bootstrap_ci.py` (`{BOOT_PATH}`)*"]
    ms = b["models"]
    lines = [
        _row(["Model (seed 0)", "Test ADE (m) [95% CI]", "Test FDE (m) [95% CI]",
              "Test scenes", "= seed-0 artifact?"]),
        _row(["---"] * 5),
    ]
    for name in b["ranking_by_ade"]:
        m = ms[name]
        match = {True: "yes", False: "**no**", None: "—"}[m["matches_seed0_artifact"]]
        lines.append(_row([DUMP_NAMES.get(name, name), f"{m['ade']:.2f} {_ci(m['ade_ci95'])}",
                           f"{m['fde']:.2f} {_ci(m['fde_ci95'])}", str(m["n_scenes"]), match]))
    lines += ["", "Paired comparisons of the seed-0 models adjacent in the ranking (same scene "
              "resample for both; negative = the first model is better):", "",
              _row(["Comparison", "ΔADE (m)", "95% CI", "Separated at 95%?"]), _row(["---"] * 4)]
    for p in b["adjacent_pairs"]:
        sep = "yes" if (p["ci95"][1] < 0 or p["ci95"][0] > 0) else "no"
        lines.append(_row([f"{DUMP_NAMES.get(p['a'], p['a'])} vs {DUMP_NAMES.get(p['b'], p['b'])}",
                           f"{p['ade_diff_a_minus_b']:+.2f}", _ci(p["ci95"]), sep]))
    sp = b.get("seed_pooled")
    if sp:
        lines += ["", f"Seed-pooled paired comparisons for the models with a dump per seed (3-seed "
                  f"means, seeds {', '.join(map(str, sp['seeds']))}). Each replicate resamples the "
                  "test scenes for both models and each model's seeds with replacement, so the CI "
                  "covers training-seed variation as well:", "",
                  _row(["Comparison", "ΔADE (m), 3-seed means", "95% CI", "Separated at 95%?",
                        "Seed pairings where the first is better"]), _row(["---"] * 5)]
        for p in sp["pairs"]:
            sep = "yes" if (p["ci95"][1] < 0 or p["ci95"][0] > 0) else "no"
            lines.append(_row([f"{DUMP_NAMES.get(p['a'], p['a'])} vs {DUMP_NAMES.get(p['b'], p['b'])}",
                               f"{p['ade_diff_a_minus_b']:+.2f}", _ci(p["ci95"]), sep,
                               f"{p['seed_pairings_a_better']} of {p['seed_pairings']}"]))
        lines += ["", "Where the two tables disagree, cite the seed-pooled row: a single seed can "
                  "be a model's luckiest or unluckiest run."]
    best = ms[b["ranking_by_ade"][0]]
    d = best.get("ade_disparity")
    if d:
        sc = {c: v["n_scenes"] for c, v in best["per_class"].items()}
        lines += ["", f"Per-class ADE disparity for {DUMP_NAMES.get(b['ranking_by_ade'][0])} "
                  f"(classes with n ≥ 50): **{d['ratio']:.1f}×**, 95% CI "
                  f"{d['ratio_ci95'][0]:.1f}–{d['ratio_ci95'][1]:.1f}× "
                  f"(worst {d['worst']}, {sc[d['worst']]} test scenes; best {d['best']}, "
                  f"{sc[d['best']]} test scenes)."]
    lines += ["", f"Source artifact: [`{BOOT_PATH}`]({BOOT_PATH}) ({b['n_boot']:,} scene "
              f"resamples of the {b['n_scenes']} test scenes)."]
    return lines


def conformal_rows() -> list[str]:
    c = _load(CONF_PATH)
    if c is None or "n_folds" not in c:
        return [f"*pending — run `python scripts/conformal_wrapper.py` (`{CONF_PATH}`)*"]
    tgt = c["target_coverage"]
    names = [n for n in DUMP_NAMES if n in c["models"]]
    lines = [
        _row(["Predictor", f"B: step coverage, mean (5–95%) over {c['n_folds']} scene folds",
              "A: val→test step coverage [95% CI]", "B folds at or below A",
              "Trajectory coverage: per-step band", "Trajectory coverage: simultaneous band",
              "Mean radius (m): per-step / simultaneous"]),
        _row(["---"] * 7),
    ]
    for n in names:
        r = c["models"][n]
        F, A = r["regime_B_scene_folds"], r["regime_A_val_to_test"]["marginal"]
        bs, bt, st = F["per_step_marginal"]["coverage"], F["per_step_marginal"]["trajectory_coverage"], \
            F["simultaneous_marginal"]["trajectory_coverage"]
        lines.append(_row([
            DUMP_NAMES[n], f"{_pct(bs['mean'])} ({_pct(bs['p05'])}–{_pct(bs['p95'])})",
            f"{_pct(A['coverage'])} [{_pct(A['coverage_ci95'][0])}, {_pct(A['coverage_ci95'][1])}]",
            f"{F['regime_A_coverage_rank_in_folds']:.0%}", _pct(bt["mean"]), _pct(st["mean"]),
            f"{F['per_step_marginal']['mean_radius_m']['mean']:.1f} / "
            f"{F['simultaneous_marginal']['mean_radius_m']['mean']:.1f}"]))
    lines += ["", f"Per-class step coverage (regime B, mean over scene folds; target {tgt:.0%}): "
              "one global radius vs per-class (Mondrian) radii:", "",
              _row(["Predictor", "Car: global → per-class", "Pedestrian: global → per-class",
                    "MotorcyleRider: global → per-class"]), _row(["---"] * 4)]
    for n in names:
        pc = c["models"][n]["regime_B_scene_folds"]["per_class_coverage_mean"]
        cell = lambda k: (f"{_pct(pc['marginal'][k])} → {_pct(pc['class_conditional'][k])}"
                          if k in pc["marginal"] else "—")
        lines.append(_row([DUMP_NAMES[n], cell("Car"), cell("Pedestrian"), cell("MotorcyleRider")]))
    lines += ["", f"Source artifact: [`{CONF_PATH}`]({CONF_PATH}) (α = {c['alpha']}, "
              f"{c['n_boot']:,} scene resamples for the regime-A CIs)."]
    return lines


def alpha_rows() -> list[str]:
    a = _load(ALPHA_PATH)
    if a is None or "n_folds" not in a:
        return [f"*pending — run `python scripts/conformal_alpha_sensitivity.py` (`{ALPHA_PATH}`)*"]
    tg = a["targets"]
    names = [n for n in DUMP_NAMES if n in a["models"]]
    head = ["Model"] + [f"{lab} @ {t:.0%}" for t in tg for lab in ("B", "A")]
    lines = [_row(head), _row(["---"] * len(head))]
    for n in names:
        m = a["models"][n]
        cells = [_pct(x) for pair in zip(m["regime_B_scene_folds"]["coverage"],
                                         m["regime_A_val_to_test"]["coverage"]) for x in pair]
        lines.append(_row([DUMP_NAMES[n]] + cells))
    lines += ["", "Mean per-step band radius (regime B, scene-fold mean) at each target:", "",
              _row(["Model"] + [f"{t:.0%}" for t in tg]), _row(["---"] * (len(tg) + 1))]
    for n in names:
        rad = a["models"][n]["regime_B_scene_folds"]["mean_radius_m"]
        lines.append(_row([DUMP_NAMES[n]] + [f"{x:.1f} m" for x in rad]))
    lines += ["", f"Source artifact: [`{ALPHA_PATH}`]({ALPHA_PATH}) "
              f"({a['n_folds']} scene folds per target)."]
    return lines


def safety_rows() -> list[str]:
    sc, lat = _load(SAFE_PATH), _load(LAT_PATH)
    if sc is None:
        return [f"*pending — run `python scripts/safety_scorecard.py` (`{SAFE_PATH}`)*"]
    lat = (lat or {}).get("packages", {})
    pop, dec = sc["population"], sc["decision"]
    lines = [
        f"Rule committed in `{(sc.get('rule_commit') or '?')[:7]}` before any of these numbers "
        f"existed. Test split: {pop['n_test']:,} agents, {pop['n_conflicts']} conflicts "
        f"({pop['n_vru_conflicts']} of them pedestrians or two-wheeler riders).", "",
        _row(["Package", "Output", "Conflict AUC [95% CI]", "Pedestrians & two-wheelers AUC",
              "Recall / false alarms at the 90% band", "Latency (ms, median)"]),
        _row(["---"] * 6),
    ]
    for name, v in sorted(sc["packages"].items(), key=lambda kv: -kv[1]["auc"]):
        out = "1 trajectory + band" if v["kind"] == "single" else f"{v['k']} futures + band"
        ms = lat.get(name, {}).get("median_ms")
        lines.append(_row([name, out, f"{v['auc']:.3f} {_ci(v['auc_ci95'], 3)}",
                           f"{v['auc_vru']:.3f} {_ci(v['auc_vru_ci95'], 3)}",
                           f"{v['recall_at_band']:.0%} / {v['far_at_band']:.0%}",
                           "—" if ms is None else f"{ms:.1f}"]))
    lines += ["", "How the pre-registered rule decided:", ""]
    lines += [f"{i}. {step}" for i, step in enumerate(dec["steps"], 1)]
    lines += ["", f"**Rule outcome: {dec['pick']}.**" if dec["pick"] else "**Rule outcome: pending.**"]
    ex = sc.get("exploratory")
    if ex:
        em = ex["emerging_conflicts"]
        best = em["best"]
        cv = em["auc"].get("CV (vel_k=5)")
        lines += ["", f"Exploratory (added after the result, not used for the pick): current "
                  f"distance alone flags conflicts with AUC {ex['auc_current_distance_only']:.3f}, "
                  f"and {ex['share_of_conflicts_within_10m_now']:.0%} of conflict agents are already "
                  f"within 10 m when the prediction is made. On the {em['n_pos']} emerging "
                  f"conflicts (more than 10 m away at prediction time), the best package is "
                  f"{best} at {em['auc'][best]['auc']:.3f}"
                  + (f", against {cv['auc']:.3f} for constant velocity" if cv else "") + "."]
    lines += ["", f"Source artifacts: [`{SAFE_PATH}`]({SAFE_PATH}), [`{LAT_PATH}`]({LAT_PATH}) "
              f"({sc['settings']['n_boot']:,} seed-pooled scene resamples; latency on "
              f"{_load(LAT_PATH)['gpu'] if _load(LAT_PATH) else '—'})."]
    return lines


def closed_loop_rows() -> list[str]:
    cl = _load(CL_PATH)
    if cl is None:
        return [f"*pending — run `python scripts/closed_loop_sim.py` (`{CL_PATH}`)*"]
    pk, dec = cl["packages"], cl["decision"]
    refs = [n for n in pk if "seeds" in pk[n] and len(pk[n]["seeds"]) == 1 and "no_band" not in pk[n]]
    ranked = sorted((n for n in pk if n not in refs), key=lambda n: -pk[n]["score"])
    lines = [
        f"Rule committed in `{(cl.get('rule_commit') or '?')[:7]}` before any learned predictor ran on "
        f"the test scenes. {cl['n_scenes']} test scenes, {pk[ranked[0]]['n_episodes']} episodes per "
        f"package and seed; 3-seed means.", "",
        _row(["Package", "Episode score [95% CI]", "At-fault collision episodes",
              "…with pedestrians / two-wheelers", "Progress", "Harsh braking", "Near misses",
              "Score without the band"]),
        _row(["---"] * 8),
    ]
    for n in ranked:
        v = pk[n]
        nb = v.get("no_band", {}).get("score")
        lines.append(_row([n, f"{v['score']:.3f} {_ci(v['score_ci95'], 3)}", f"{v['at_fault_rate']:.1%}",
                           f"{v['at_fault_vru_rate']:.1%}", f"{v['progress']:.2f}",
                           f"{v['harsh_braking_rate']:.0%}", f"{v['near_miss_rate']:.0%}",
                           "—" if nb is None else f"{nb:.3f}"]))
    for n in refs:
        v = pk[n]
        lines.append(_row([f"*{n}* (reference)", f"{v['score']:.3f}", f"{v['at_fault_rate']:.1%}",
                           f"{v['at_fault_vru_rate']:.1%}", f"{v['progress']:.2f}",
                           f"{v['harsh_braking_rate']:.0%}", f"{v['near_miss_rate']:.0%}", "—"]))
    if dec:
        lines += ["", "How the pre-registered rule decided:", ""]
        lines += [f"{i}. {step}" for i, step in enumerate(dec["steps"], 1)]
        lines += ["", f"**Rule outcome: {dec['pick']}.**" if dec["pick"] else "**Rule outcome: pending.**"]
    lines += ["", f"Source artifact: [`{CL_PATH}`]({CL_PATH}) ({cl['settings']['n_boot']:,} seed-pooled "
              f"scene resamples)."]
    return lines


def splice(text: str, begin: str, end: str, body: list[str]) -> str:
    i = text.find(begin)
    j = text.find(end)
    if i == -1 or j == -1 or j < i:
        raise SystemExit(f"README markers not found or malformed: {begin!r} ... {end!r}")
    return text[: i + len(begin)] + "\n" + "\n".join(body) + "\n" + text[j:]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if README tables are stale")
    args = ap.parse_args()

    text = README.read_text(encoding="utf-8")
    new = splice(text, BEGIN_V2, END_V2, v2_rows())
    new = splice(new, BEGIN_AUDIT, END_AUDIT, audit_rows())
    new = splice(new, BEGIN_GAP, END_GAP, gap_rows())
    new = splice(new, BEGIN_BOOT, END_BOOT, bootstrap_rows())
    new = splice(new, BEGIN_CONF, END_CONF, conformal_rows())
    new = splice(new, BEGIN_ALPHA, END_ALPHA, alpha_rows())
    new = splice(new, BEGIN_SAFE, END_SAFE, safety_rows())
    if BEGIN_CL in new:
        new = splice(new, BEGIN_CL, END_CL, closed_loop_rows())
    new = splice(new, BEGIN_WORLD, END_WORLD, world_rows())
    new = splice(new, BEGIN_LEGACY, END_LEGACY, legacy_rows())

    if args.check:
        if new != text:
            print("README results tables are STALE relative to outputs/*.json.")
            print("Run: python scripts/make_tables.py  — and commit the result.")
            return 1
        print("README results tables match the committed artifacts.")
        return 0

    if new != text:
        README.write_text(new, encoding="utf-8")
        print(f"updated {README}")
    else:
        print("README already up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
