"""Generate results tables in README.md from committed metrics JSONs.

Provenance rule: a number may appear in a results table ONLY if it is read
from a metrics JSON in the repository. This script is the single source of
truth for those tables; CI runs `make_tables.py --check` and fails if the
README tables have drifted from the artifacts (e.g. a hand-edited number).

Usage:
    python scripts/make_tables.py            # rewrite README tables in place
    python scripts/make_tables.py --check    # exit 1 if README is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
README = REPO / "README.md"

BEGIN_WORLD = "<!-- BEGIN AUTOGENERATED: world-frame results (scripts/make_tables.py) -->"
END_WORLD = "<!-- END AUTOGENERATED: world-frame results -->"
BEGIN_LEGACY = "<!-- BEGIN AUTOGENERATED: legacy ego-frame results (scripts/make_tables.py) -->"
END_LEGACY = "<!-- END AUTOGENERATED: legacy ego-frame results -->"


def _load(path: str) -> dict | None:
    p = REPO / path
    if not p.exists():
        return None
    return json.loads(p.read_text(encoding="utf-8"))


def _fmt(x: float | None) -> str:
    return f"{x:.2f}" if isinstance(x, (int, float)) else "—"


def _row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


