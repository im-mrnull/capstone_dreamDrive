def _pm(mean: float, std: float) -> str:
    return f"{mean:.2f}" if std < 1e-9 else f"{mean:.2f} ± {std:.2f}"


def v2_rows() -> list[str]:
    lines = [
        _row(["Model", "K", "Deployable single output?", "Test ADE (m)", "Test FDE (m)",
              "Val ADE (m)", "Seeds"]),
        _row(["---"] * 7),
    ]
    summary = _load(SUMMARY_PATH)
    if summary is None:
        lines.append(_row(["*benchmark v2 not yet run*", "—", "—", "—", "—", "—",
                           f"`{SUMMARY_PATH}` *(not yet generated)*"]))
        return lines
    for m in summary["models"]:
        dep = "yes" if m["deployable"] else "no (oracle)"
        if m.get("status") != "ok":
            lines.append(_row([m["label"], str(m["k"]), dep, "*pending*", "*pending*",
                               "*pending*", "—"]))
            continue
        lines.append(_row([
            m["label"], str(m["k"]), dep,
            _pm(m["test_ade_mean"], m["test_ade_std"]),
            _pm(m["test_fde_mean"], m["test_fde_std"]),
            _pm(m["val_ade_mean"], m["val_ade_std"]),
            ",".join(str(s) for s in m["seeds"]),
        ]))
    lines.append("")
    lines.append(f"Source artifact: [`{SUMMARY_PATH}`]({SUMMARY_PATH}) "
                 "(aggregated from per-seed metrics JSONs in the same directory).")
    return lines


def audit_rows() -> list[str]:
    header = [
        _row(["Class", "n", "ADE (m)", "FDE (m)", "Mean GT path (m)", "ADE per path-meter"]),
        _row(["---"] * 6),
    ]
    summary = _load(SUMMARY_PATH)
    if summary is None:
        return header + [_row(["*benchmark v2 not yet run*", "—", "—", "—", "—", "—"])]
    deployable = [m for m in summary["models"]
                  if m.get("status") == "ok" and m["deployable"] and m.get("per_class_test_seed_last")]
    if not deployable:
        return header + [_row(["*pending*", "—", "—", "—", "—", "—"])]
    best = min(deployable, key=lambda m: m["test_ade_mean"])
    pc = best["per_class_test_seed_last"]
    lines = [f"Best deployable model on test: **{best['label']}** "
             f"(per-class stats from one representative seed)."]
    if best["label"].startswith("Trajectron++"):
        lines.append("Note: Trajectron++ is evaluated at every valid timestep, so `n` counts "
                     "node@timestep prediction instances — denser than the one-window-per-agent "
                     "counts of the other models, but over the same test scenes.")
    lines += [""] + header
    classes = sorted(pc["classes"].items(), key=lambda kv: -kv[1]["n"])
    for cls, v in classes:
        if v["n"] < pc["min_class_n"]:
            continue
        app = f"{v['ade_per_path']:.3f}" if v.get("ade_per_path") is not None else "—"
        lines.append(_row([cls, str(v["n"]), f"{v['ade']:.2f}", f"{v['fde']:.2f}",
                           f"{v['mean_gt_path_m']:.1f}", app]))
    disp = pc.get("ade_disparity_worst_over_best")
    lines.append("")
    lines.append(f"ADE disparity (worst/best class, n ≥ {pc['min_class_n']}): "
                 + (f"**{disp:.2f}×**" if disp else "—"))
    return lines


def gap_rows() -> list[str]:
    summary = _load(SUMMARY_PATH)
    gap = (summary or {}).get("trajectronpp_gap_decomposition")
    if not gap:
        return ["*Trajectron++ gap decomposition not yet generated (run the benchmark).*"]
    lines = [
        _row(["Readout", "Test ADE (m)", "Meaning"]),
        _row(["---"] * 3),
        _row([f"Random single sample (best-of-1 ≈ mean-sample)",
              f"{gap['mean_sample_ade']:.2f}", "one draw, blind"]),
        _row(["**Most-likely (deployable)**", f"**{gap['most_likely_ade']:.2f}**",
              "argmax latent + GMM mode"]),
        _row([f"Oracle best-of-{gap['k_list'][-1]}", f"{gap['oracle_best_of_k_ade']:.2f}",
              "min over samples, picked in hindsight"]),
    ]
    curve = " → ".join(f"{v:.2f}" for v in gap["best_of_k_ade_mean"])
    klabel = ", ".join(str(k) for k in gap["k_list"])
    lines += [
        "",
        f"Best-of-K curve (K = {klabel}): **{curve}**.",
        "",
        f"- **Calibration value = {gap['calibration_value_m']:.2f} m** "
        "(random draw → most-likely): the deployable mode beats a random sample — "
        "the mode selection is genuinely informative.",
        f"- **Coverage value = {gap['coverage_value_m']:.2f} m** "
        "(most-likely → oracle): the irreducible cost of committing to one future. "
        "The curve is still falling at the largest K, the signature of genuine "
        "multimodality rather than sampling noise — only multiple deployed modes can close it.",
        "",
        f"Source artifact: [`{SUMMARY_PATH}`]({SUMMARY_PATH}) "
        "(`trajectronpp_gap_decomposition`, 3-seed test mean).",
    ]
    return lines


def splice(text: str, begin: str, end: str, body: list[str]) -> str:
    i = text.find(begin)
    j = text.find(end)
    if i == -1 or j == -1 or j < i:
        raise SystemExit(f"README markers not found or malformed: {begin!r} ... {end!r}")
    return text[: i + len(begin)] + "\n" + "\n".join(body) + "\n" + text[j:]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if README tables are stale")
    args = ap.parse_args()

    text = README.read_text(encoding="utf-8")
    new = splice(text, BEGIN_V2, END_V2, v2_rows())
    new = splice(new, BEGIN_AUDIT, END_AUDIT, audit_rows())
    new = splice(new, BEGIN_GAP, END_GAP, gap_rows())
    new = splice(new, BEGIN_WORLD, END_WORLD, world_rows())
    new = splice(new, BEGIN_LEGACY, END_LEGACY, legacy_rows())

    if args.check:
        if new != text:
            print("README results tables are STALE relative to outputs/*.json.")
            print("Run: python scripts/make_tables.py  — and commit the result.")
            return 1
        print("README results tables match the committed artifacts.")
        return 0

    if new != text:
        README.write_text(new, encoding="utf-8")
        print(f"updated {README}")
    else:
        print("README already up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
