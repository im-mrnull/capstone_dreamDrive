"""Train/evaluate a minimal ST-GAT-style model on the exported ST-GAT dataset.

This is a lightweight, repo-independent implementation that uses:
- LSTM encoder per agent over observed relative displacements
- Single graph-attention pooling over agents at the end of observation
- LSTMCell decoder to generate future relative displacements

Input dataset:
- outputs/stgat_dataset_obs20_pred60.npz (generated by scripts/export_stgat_format.py)

Outputs:
- metrics JSON with ADE/FDE on a scene-level val split
- optional predictions NPZ
- checkpoint

Note: This is *ST-GAT-inspired*, not a byte-for-byte reproduction of a specific paper repo.
It is intended as a strong multi-agent neural baseline compatible with your data.
"""

from __future__ import annotations

import argparse
import json
import math
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
import torch
from torch import nn
from torch.utils.data import DataLoader, Dataset


def set_seed(seed: int) -> None:
    torch.manual_seed(seed)
    np.random.seed(seed)


@dataclass
class Batch:
    obs_abs: torch.Tensor      # (B, M, 2, obs_len)
    pred_abs: torch.Tensor     # (B, M, 2, pred_len)
    obs_rel: torch.Tensor      # (B, M, 2, obs_len)
    pred_rel: torch.Tensor     # (B, M, 2, pred_len)
    agent_mask: torch.Tensor   # (B, M) bool


class STGATSeqDataset(Dataset):
    def __init__(
        self,
        npz_path: Path,
        split: str,
        val_frac: float,
        seed: int,
        split_by_scene: bool = True,
    ) -> None:
        super().__init__()
        data = np.load(npz_path, allow_pickle=True)
        self.obs_traj = data["obs_traj"].astype(np.float32)          # (N, 2, obs)
        self.pred_traj = data["pred_traj"].astype(np.float32)        # (N, 2, pred)
        self.obs_traj_rel = data["obs_traj_rel"].astype(np.float32)  # (N, 2, obs)
        self.pred_traj_rel = data["pred_traj_rel"].astype(np.float32)# (N, 2, pred)
        self.seq_start_end = data["seq_start_end"].astype(np.int64)  # (S, 2)
        self.scene_id = data["scene_id"].astype(object) if "scene_id" in data else None

        self.num_seqs = int(self.seq_start_end.shape[0])
        if self.scene_id is None or not split_by_scene:
            rng = np.random.default_rng(seed)
            idx = np.arange(self.num_seqs)
            rng.shuffle(idx)
            n_val = max(1, int(round(self.num_seqs * float(val_frac))))
            val_set = set(idx[:n_val].tolist())
            keep = [i for i in range(self.num_seqs) if (i in val_set) == (split == "val")]
            self.seq_indices = np.asarray(keep, dtype=np.int64)
            self.split_kind = "random"
        else:
            rng = np.random.default_rng(seed)
            unique_scenes = np.unique(self.scene_id)
            rng.shuffle(unique_scenes)
            n_val = max(1, int(round(len(unique_scenes) * float(val_frac))))
            val_scenes = set(unique_scenes[:n_val].tolist())
            keep = []
            for i in range(self.num_seqs):
                sid = self.scene_id[i]
                is_val = sid in val_scenes
                if (split == "val" and is_val) or (split == "train" and not is_val):
                    keep.append(i)
            self.seq_indices = np.asarray(keep, dtype=np.int64)
            self.split_kind = "scene"

    def __len__(self) -> int:
        return int(self.seq_indices.shape[0])

    def __getitem__(self, idx: int) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
        seq_i = int(self.seq_indices[idx])
        s, e = self.seq_start_end[seq_i]
        obs = self.obs_traj[s:e]          # (M, 2, obs)
        pred = self.pred_traj[s:e]        # (M, 2, pred)
        obs_rel = self.obs_traj_rel[s:e]  # (M, 2, obs)
        pred_rel = self.pred_traj_rel[s:e]# (M, 2, pred)
        return obs, pred, obs_rel, pred_rel


def collate_pad(batch_items: List[Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]]) -> Batch:
    # Items: (obs, pred, obs_rel, pred_rel) each (M_i, 2, T)
    B = len(batch_items)
    obs_len = batch_items[0][0].shape[-1]
    pred_len = batch_items[0][1].shape[-1]
    max_m = max(item[0].shape[0] for item in batch_items)

    obs_abs = torch.zeros((B, max_m, 2, obs_len), dtype=torch.float32)
    pred_abs = torch.zeros((B, max_m, 2, pred_len), dtype=torch.float32)
    obs_rel = torch.zeros((B, max_m, 2, obs_len), dtype=torch.float32)
    pred_rel = torch.zeros((B, max_m, 2, pred_len), dtype=torch.float32)
    agent_mask = torch.zeros((B, max_m), dtype=torch.bool)

    for b, (o, p, orl, prl) in enumerate(batch_items):
        m = o.shape[0]
        obs_abs[b, :m] = torch.from_numpy(o)
        pred_abs[b, :m] = torch.from_numpy(p)
        obs_rel[b, :m] = torch.from_numpy(orl)
        pred_rel[b, :m] = torch.from_numpy(prl)
        agent_mask[b, :m] = True

    return Batch(
        obs_abs=obs_abs,
        pred_abs=pred_abs,
        obs_rel=obs_rel,
        pred_rel=pred_rel,
        agent_mask=agent_mask,
    )


class AgentSelfAttentionLayer(nn.Module):
    """Multi-head self-attention over agents (message passing).

    This replaces the earlier single-head pooling with a deeper, standard recipe:
    MHA + residual + LayerNorm + FFN.
    """

    def __init__(self, hidden_dim: int, num_heads: int, dropout: float) -> None:
        super().__init__()
        self.mha = nn.MultiheadAttention(
            embed_dim=hidden_dim,
            num_heads=num_heads,
            dropout=dropout,
            batch_first=True,
        )
        self.ln1 = nn.LayerNorm(hidden_dim)
        self.ff = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim * 4),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim * 4, hidden_dim),
        )
        self.ln2 = nn.LayerNorm(hidden_dim)
        self.drop = nn.Dropout(dropout)

    def forward(self, h: torch.Tensor, agent_mask: torch.Tensor) -> torch.Tensor:
        # h: (B, M, H), agent_mask: (B, M) where True indicates a real agent
        key_padding_mask = ~agent_mask  # True means "ignore" for MultiheadAttention
        attn_out, _ = self.mha(h, h, h, key_padding_mask=key_padding_mask, need_weights=False)
        h = self.ln1(h + self.drop(attn_out))
        h2 = self.ff(h)
        h = self.ln2(h + self.drop(h2))
        return h


class GraphAttentionPool(nn.Module):
    """Single-step attention pooling (original simple baseline)."""

    def __init__(self, hidden_dim: int, attn_dim: int) -> None:
        super().__init__()
        self.q = nn.Linear(hidden_dim, attn_dim)
        self.k = nn.Linear(hidden_dim, attn_dim)
        self.v = nn.Linear(hidden_dim, attn_dim)
        self.out = nn.Linear(hidden_dim + attn_dim, hidden_dim)

    def forward(self, h: torch.Tensor, mask: torch.Tensor) -> torch.Tensor:
        # h: (B, M, H), mask: (B, M)
        B, M, _ = h.shape
        q = self.q(h)  # (B, M, D)
        k = self.k(h)  # (B, M, D)
        v = self.v(h)  # (B, M, D)

        scale = 1.0 / math.sqrt(k.shape[-1])
        scores = torch.matmul(q, k.transpose(1, 2)) * scale  # (B, M, M)

        key_mask = mask.unsqueeze(1).expand(B, M, M)
        neg_inf = torch.finfo(scores.dtype).min
        scores = scores.masked_fill(~key_mask, neg_inf)

        query_mask = mask.unsqueeze(2).expand(B, M, M)
        scores = scores.masked_fill(~query_mask, 0.0)

        attn = torch.softmax(scores, dim=-1)
        attn = attn * query_mask.float()

        ctx = torch.matmul(attn, v)  # (B, M, D)
        fused = torch.cat([h, ctx], dim=-1)
        return torch.tanh(self.out(fused))


class STGATModel(nn.Module):
    def __init__(
        self,
        obs_len: int,
        pred_len: int,
        emb_dim: int = 32,
        hidden_dim: int = 128,
        pool: str = "simple",
        attn_dim: int = 64,
        num_heads: int = 4,
        gat_layers: int = 2,
        dropout: float = 0.0,
    ) -> None:
        super().__init__()
        self.obs_len = obs_len
        self.pred_len = pred_len

        self.emb = nn.Linear(2, emb_dim)
        self.encoder = nn.LSTM(
            input_size=emb_dim,
            hidden_size=hidden_dim,
            num_layers=1,
            batch_first=True,
            dropout=0.0,
        )
        self.pool_type = str(pool)
        if self.pool_type not in {"simple", "mha"}:
            raise ValueError("pool must be one of: simple, mha")

        self.simple_pool = GraphAttentionPool(hidden_dim=hidden_dim, attn_dim=attn_dim)

        if hidden_dim % num_heads != 0:
            raise ValueError(f"hidden_dim ({hidden_dim}) must be divisible by num_heads ({num_heads})")

        self.mha_layers = nn.ModuleList(
            [AgentSelfAttentionLayer(hidden_dim=hidden_dim, num_heads=num_heads, dropout=dropout) for _ in range(gat_layers)]
        )

        self.dec_in = nn.Linear(2, emb_dim)
        self.decoder_cell = nn.LSTMCell(input_size=emb_dim, hidden_size=hidden_dim)
        self.out = nn.Linear(hidden_dim, 2)
        self.drop = nn.Dropout(dropout)

    def forward(
        self,
        obs_rel: torch.Tensor,
        agent_mask: torch.Tensor,
        teacher_forcing: bool,
        gt_pred_rel: torch.Tensor | None = None,
    ) -> torch.Tensor:
        # obs_rel: (B, M, 2, obs_len)
        B, M, _, obs_len = obs_rel.shape
        assert obs_len == self.obs_len

        # Encode per agent
        x = obs_rel.permute(0, 1, 3, 2).contiguous()  # (B, M, obs_len, 2)
        x = x.view(B * M, obs_len, 2)
        x = self.drop(torch.relu(self.emb(x)))
        enc_out, (h_n, c_n) = self.encoder(x)
        h_last = h_n[-1].view(B, M, -1)  # (B, M, H)

        # Pool across agents
        if self.pool_type == "simple":
            h0 = self.simple_pool(h_last, agent_mask)
        else:
            h0 = h_last
            for layer in self.mha_layers:
                h0 = layer(h0, agent_mask)

        # Decode
        h = h0.reshape(B * M, -1)
        c = torch.zeros_like(h)

        preds = []

        prev_rel = obs_rel[:, :, :, -1].permute(0, 1, 2).contiguous()  # (B, M, 2)
        prev_rel = prev_rel.view(B * M, 2)

        for t in range(self.pred_len):
            inp = self.drop(torch.relu(self.dec_in(prev_rel)))
            h, c = self.decoder_cell(inp, (h, c))
            step = self.out(self.drop(h))  # (B*M, 2)
            preds.append(step.view(B, M, 2))

            if teacher_forcing and gt_pred_rel is not None:
                prev_rel = gt_pred_rel[:, :, :, t].permute(0, 1, 2).contiguous().view(B * M, 2)
            else:
                prev_rel = step

        pred_rel_hat = torch.stack(preds, dim=-1)  # (B, M, 2, pred_len)
        return pred_rel_hat


def masked_loss(pred: torch.Tensor, gt: torch.Tensor, mask: torch.Tensor, kind: str) -> torch.Tensor:
    """Compute masked loss over agents.

    pred/gt: (B, M, 2, T)
    mask: (B, M) where True indicates a real agent.
    """
    m = mask.unsqueeze(2).unsqueeze(3).float()
    if kind == "mse":
        diff = (pred - gt) * m
        return (diff * diff).sum() / (m.sum().clamp_min(1.0) * pred.shape[2] * pred.shape[3])
    if kind == "huber":
        # Smooth L1 (Huber) is often a bit more stable for long horizons.
        diff = (pred - gt) * m
        loss = torch.nn.functional.smooth_l1_loss(diff, torch.zeros_like(diff), reduction="sum")
        return loss / (m.sum().clamp_min(1.0) * pred.shape[2] * pred.shape[3])
    raise ValueError(f"unknown loss kind: {kind}")


def teacher_forcing_ratio(epoch: int, tf_start: float, tf_end: float, tf_decay_epochs: int) -> float:
    if tf_decay_epochs <= 0:
        return float(tf_end)
    if epoch <= 1:
        return float(tf_start)
    t = min(1.0, max(0.0, (epoch - 1) / float(tf_decay_epochs)))
    return float(tf_start + (tf_end - tf_start) * t)


@torch.no_grad()
def ade_fde_from_rel(
    obs_abs: torch.Tensor,
    pred_abs_gt: torch.Tensor,
    pred_rel_hat: torch.Tensor,
    mask: torch.Tensor,
) -> Tuple[float, float]:
    # obs_abs: (B,M,2,obs)
    # pred_abs_gt: (B,M,2,pred)
    # pred_rel_hat: (B,M,2,pred)
    start = obs_abs[:, :, :, -1]  # (B,M,2)
    pred_abs_hat = start.unsqueeze(-1) + torch.cumsum(pred_rel_hat, dim=-1)

    err = torch.linalg.vector_norm((pred_abs_hat - pred_abs_gt).permute(0, 1, 3, 2), dim=-1)  # (B,M,T)
    m = mask.float()  # (B,M)
    denom = m.sum().clamp_min(1.0)
    ade = (err * m.unsqueeze(-1)).sum() / (denom * err.shape[-1])
    fde = (err[:, :, -1] * m).sum() / denom
    return float(ade.item()), float(fde.item())


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="outputs/stgat_dataset_obs20_pred60.npz")
    ap.add_argument("--out-dir", default="outputs/baselines")
    ap.add_argument("--save-metrics-json", default="outputs/baselines/stgat_metrics_obs20_pred60.json")
    ap.add_argument("--save-ckpt", default="outputs/baselines/stgat_ckpt_obs20_pred60.pt")
    ap.add_argument("--save-pred-npz", default="outputs/baselines/stgat_pred_val_obs20_pred60.npz")

    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--val-frac", type=float, default=0.2)
    ap.add_argument("--split-by-scene", action="store_true", default=True)
    ap.add_argument("--no-split-by-scene", dest="split_by_scene", action="store_false")

    ap.add_argument("--epochs", type=int, default=40)
    ap.add_argument("--batch-size", type=int, default=16)
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--weight-decay", type=float, default=1e-4)

    ap.add_argument("--loss", choices=["mse", "huber"], default="mse")

    ap.add_argument("--patience", type=int, default=0, help="Early stopping patience on val ADE (0 disables)")
    ap.add_argument(
        "--lr-plateau",
        action="store_true",
        default=True,
        help="Use ReduceLROnPlateau on val ADE",
    )
    ap.add_argument("--no-lr-plateau", dest="lr_plateau", action="store_false")
    ap.add_argument("--lr-plateau-factor", type=float, default=0.5)
    ap.add_argument("--lr-plateau-patience", type=int, default=8)
    ap.add_argument("--min-lr", type=float, default=1e-6)

    ap.add_argument("--amp", action="store_true", default=True, help="Enable AMP (CUDA only)")
    ap.add_argument("--no-amp", dest="amp", action="store_false")

    ap.add_argument("--tf-start", type=float, default=1.0, help="Teacher forcing ratio at epoch 1")
    ap.add_argument("--tf-end", type=float, default=0.0, help="Teacher forcing ratio after decay")
    ap.add_argument("--tf-decay-epochs", type=int, default=40, help="Linear decay duration in epochs")

    ap.add_argument("--emb-dim", type=int, default=32)
    ap.add_argument("--hidden-dim", type=int, default=128)
    ap.add_argument("--pool", choices=["simple", "mha"], default="simple")
    ap.add_argument("--attn-dim", type=int, default=64, help="Only used for --pool simple")
    ap.add_argument("--num-heads", type=int, default=4)
    ap.add_argument("--gat-layers", type=int, default=2)
    ap.add_argument("--dropout", type=float, default=0.0)

    ap.add_argument("--device", default="cpu")
    args = ap.parse_args()

    device = torch.device(args.device)

    set_seed(int(args.seed))

    data_path = Path(args.data)
    train_ds = STGATSeqDataset(
        npz_path=data_path,
        split="train",
        val_frac=float(args.val_frac),
        seed=int(args.seed),
        split_by_scene=bool(args.split_by_scene),
    )
    val_ds = STGATSeqDataset(
        npz_path=data_path,
        split="val",
        val_frac=float(args.val_frac),
        seed=int(args.seed),
        split_by_scene=bool(args.split_by_scene),
    )

    # Infer lengths from first item
    obs0, pred0, _, _ = train_ds[0]
    obs_len = obs0.shape[-1]
    pred_len = pred0.shape[-1]

    train_loader = DataLoader(
        train_ds,
        batch_size=int(args.batch_size),
        shuffle=True,
        num_workers=0,
        collate_fn=collate_pad,
    )
    val_loader = DataLoader(
        val_ds,
        batch_size=int(args.batch_size),
        shuffle=False,
        num_workers=0,
        collate_fn=collate_pad,
    )

    model = STGATModel(
        obs_len=obs_len,
        pred_len=pred_len,
        emb_dim=int(args.emb_dim),
        hidden_dim=int(args.hidden_dim),
        pool=str(args.pool),
        attn_dim=int(args.attn_dim),
        num_heads=int(args.num_heads),
        gat_layers=int(args.gat_layers),
        dropout=float(args.dropout),
    ).to(device)

    opt = torch.optim.AdamW(model.parameters(), lr=float(args.lr), weight_decay=float(args.weight_decay))

    scaler = torch.cuda.amp.GradScaler(enabled=bool(args.amp) and device.type == "cuda")

    scheduler = None
    if bool(args.lr_plateau):
        scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
            opt,
            mode="min",
            factor=float(args.lr_plateau_factor),
            patience=int(args.lr_plateau_patience),
            min_lr=float(args.min_lr),
            verbose=False,
        )

    best_val_ade = float("inf")
    best_epoch = -1
    best_val_fde = float("inf")
    patience_left = int(args.patience)

    for epoch in range(1, int(args.epochs) + 1):
        model.train()
        train_losses = []
        tf_ratio = teacher_forcing_ratio(epoch, float(args.tf_start), float(args.tf_end), int(args.tf_decay_epochs))
        for batch in train_loader:
            batch = Batch(
                obs_abs=batch.obs_abs.to(device),
                pred_abs=batch.pred_abs.to(device),
                obs_rel=batch.obs_rel.to(device),
                pred_rel=batch.pred_rel.to(device),
                agent_mask=batch.agent_mask.to(device),
            )

            use_tf = (torch.rand(()) < tf_ratio).item()  # stochastic scheduled sampling
            opt.zero_grad(set_to_none=True)

            with torch.cuda.amp.autocast(enabled=scaler.is_enabled()):
                pred_rel_hat = model(
                    obs_rel=batch.obs_rel,
                    agent_mask=batch.agent_mask,
                    teacher_forcing=bool(use_tf),
                    gt_pred_rel=batch.pred_rel,
                )
                loss = masked_loss(pred_rel_hat, batch.pred_rel, batch.agent_mask, kind=str(args.loss))

            scaler.scale(loss).backward()
            scaler.unscale_(opt)
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            scaler.step(opt)
            scaler.update()

            train_losses.append(float(loss.item()))

        # Val
        model.eval()
        val_ades = []
        val_fdes = []
        for batch in val_loader:
            batch = Batch(
                obs_abs=batch.obs_abs.to(device),
                pred_abs=batch.pred_abs.to(device),
                obs_rel=batch.obs_rel.to(device),
                pred_rel=batch.pred_rel.to(device),
                agent_mask=batch.agent_mask.to(device),
            )
            pred_rel_hat = model(
                obs_rel=batch.obs_rel,
                agent_mask=batch.agent_mask,
                teacher_forcing=False,
                gt_pred_rel=None,
            )
            ade, fde = ade_fde_from_rel(batch.obs_abs, batch.pred_abs, pred_rel_hat, batch.agent_mask)
            val_ades.append(ade)
            val_fdes.append(fde)

        val_ade = float(np.nanmean(val_ades))
        val_fde = float(np.nanmean(val_fdes))
        train_loss = float(np.mean(train_losses))

        if scheduler is not None:
            scheduler.step(val_ade)

        lr_now = float(opt.param_groups[0]["lr"])

        improved = val_ade < best_val_ade - 1e-6
        if improved:
            best_val_ade = val_ade
            best_val_fde = val_fde
            best_epoch = epoch
            patience_left = int(args.patience)
            ckpt_path = Path(args.save_ckpt)
            ckpt_path.parent.mkdir(parents=True, exist_ok=True)
            torch.save(
                {
                    "model": model.state_dict(),
                    "epoch": epoch,
                    "val_ade": val_ade,
                    "val_fde": val_fde,
                    "args": vars(args),
                },
                ckpt_path,
            )
        elif int(args.patience) > 0:
            patience_left -= 1

        if epoch == 1 or epoch % 5 == 0 or improved:
            print(
                f"epoch {epoch:3d} | lr={lr_now:.2e} | tf={tf_ratio:.2f} | train_loss={train_loss:.6f} | val_ADE={val_ade:.4f} | val_FDE={val_fde:.4f}"
                + ("  (best)" if improved else "")
            )

        if int(args.patience) > 0 and patience_left <= 0:
            print(f"early stopping at epoch {epoch} (best_epoch={best_epoch}, best_val_ADE={best_val_ade:.4f})")
            break

    # Reload best
    ckpt = torch.load(Path(args.save_ckpt), map_location=device)
    model.load_state_dict(ckpt["model"])

    # Final val predictions
    # Note: number of agents per sequence varies; batches are padded to different M.
    # We pad all batches to a global max_M so we can concatenate along batch dimension.
    model.eval()
    with torch.no_grad():
        global_max_m = 0
        for batch in val_loader:
            global_max_m = max(global_max_m, int(batch.agent_mask.shape[1]))

        all_pred_abs: List[torch.Tensor] = []
        all_gt_abs: List[torch.Tensor] = []
        all_masks: List[torch.Tensor] = []

        for batch in val_loader:
            batch = Batch(
                obs_abs=batch.obs_abs.to(device),
                pred_abs=batch.pred_abs.to(device),
                obs_rel=batch.obs_rel.to(device),
                pred_rel=batch.pred_rel.to(device),
                agent_mask=batch.agent_mask.to(device),
            )
            pred_rel_hat = model(batch.obs_rel, batch.agent_mask, teacher_forcing=False, gt_pred_rel=None)
            start = batch.obs_abs[:, :, :, -1]
            pred_abs_hat = start.unsqueeze(-1) + torch.cumsum(pred_rel_hat, dim=-1)

            B, m_batch, _, Tpred = pred_abs_hat.shape
            if m_batch < global_max_m:
                pad_pred = torch.zeros((B, global_max_m, 2, Tpred), dtype=pred_abs_hat.dtype, device=pred_abs_hat.device)
                pad_gt = torch.zeros((B, global_max_m, 2, Tpred), dtype=batch.pred_abs.dtype, device=batch.pred_abs.device)
                pad_mask = torch.zeros((B, global_max_m), dtype=batch.agent_mask.dtype, device=batch.agent_mask.device)
                pad_pred[:, :m_batch] = pred_abs_hat
                pad_gt[:, :m_batch] = batch.pred_abs
                pad_mask[:, :m_batch] = batch.agent_mask
                pred_abs_hat = pad_pred
                pred_abs_gt = pad_gt
                mask = pad_mask
            else:
                pred_abs_gt = batch.pred_abs
                mask = batch.agent_mask

            all_pred_abs.append(pred_abs_hat.detach().cpu())
            all_gt_abs.append(pred_abs_gt.detach().cpu())
            all_masks.append(mask.detach().cpu())

    pred_abs_hat = torch.cat(all_pred_abs, dim=0).numpy()
    gt_abs = torch.cat(all_gt_abs, dim=0).numpy()
    masks = torch.cat(all_masks, dim=0).numpy()

    metrics = {
        "model": "STGAT_minimal",
        "data": str(data_path).replace("\\", "/"),
        "obs_len": int(obs_len),
        "pred_len": int(pred_len),
        "split": train_ds.split_kind,
        "seed": int(args.seed),
        "val_frac": float(args.val_frac),
        "train_seqs": int(len(train_ds)),
        "val_seqs": int(len(val_ds)),
        "best_epoch": int(best_epoch),
        "best_val_ade": float(best_val_ade),
        "best_val_fde": float(best_val_fde),
        "device": str(device),
        "hyper": {
            "emb_dim": int(args.emb_dim),
            "hidden_dim": int(args.hidden_dim),
            "pool": str(args.pool),
            "attn_dim": int(args.attn_dim),
            "num_heads": int(args.num_heads),
            "gat_layers": int(args.gat_layers),
            "dropout": float(args.dropout),
            "batch_size": int(args.batch_size),
            "epochs": int(args.epochs),
            "lr": float(args.lr),
            "weight_decay": float(args.weight_decay),
            "loss": str(args.loss),
            "patience": int(args.patience),
            "lr_plateau": bool(args.lr_plateau),
            "amp": bool(args.amp) and device.type == "cuda",
            "tf_start": float(args.tf_start),
            "tf_end": float(args.tf_end),
            "tf_decay_epochs": int(args.tf_decay_epochs),
        },
        "when": datetime.now().isoformat(timespec="seconds"),
        "note": "ST-GAT-inspired v2: LSTM encoder + multi-head self-attention message passing + scheduled sampling + LR plateau + AMP.",
    }

    Path(args.save_metrics_json).parent.mkdir(parents=True, exist_ok=True)
    with open(args.save_metrics_json, "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2)

    np.savez_compressed(
        args.save_pred_npz,
        pred_abs=pred_abs_hat.astype(np.float32),
        gt_abs=gt_abs.astype(np.float32),
        mask=masks.astype(bool),
    )

    print(f"saved metrics: {args.save_metrics_json}")
    print(f"saved ckpt:    {args.save_ckpt}")
    print(f"saved preds:   {args.save_pred_npz}")

    return 0


