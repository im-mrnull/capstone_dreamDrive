"""Train/evaluate an MFP (Multi-Future Prediction) baseline on our ST-GAT-format dataset.

Here "MFP" means a simple multi-modal predictor that outputs K possible futures per agent
and trains with a best-of-K ("variety") loss.

Dataset input:
- outputs/stgat_dataset_obs20_pred60.npz (generated by scripts/export_stgat_format.py)

Outputs:
- metrics JSON with best-of-K ADE/FDE on a scene-level val split
- checkpoint (.pt)
- optional val predictions NPZ (best-mode only + chosen mode index)

This is a lightweight implementation intended as a strong multi-agent, multi-modal baseline
compatible with the rest of this workspace.
"""

