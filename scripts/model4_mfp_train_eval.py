    set_seed(int(args.seed))

    data_path = Path(args.data)
    train_ds = STGATSeqDataset(
        npz_path=data_path,
        split="train",
        val_frac=float(args.val_frac),
        seed=int(args.seed),
        split_by_scene=bool(args.split_by_scene),
    )
    val_ds = STGATSeqDataset(
        npz_path=data_path,
        split="val",
        val_frac=float(args.val_frac),
        seed=int(args.seed),
        split_by_scene=bool(args.split_by_scene),
    )

    obs0, pred0, _, _ = train_ds[0]
    obs_len = obs0.shape[-1]
    pred_len = pred0.shape[-1]

    train_loader = DataLoader(train_ds, batch_size=int(args.batch_size), shuffle=True, num_workers=0, collate_fn=collate_pad)
    val_loader = DataLoader(val_ds, batch_size=int(args.batch_size), shuffle=False, num_workers=0, collate_fn=collate_pad)

    model = MFPModel(
        obs_len=obs_len,
        pred_len=pred_len,
        k=int(args.k),
        emb_dim=int(args.emb_dim),
        hidden_dim=int(args.hidden_dim),
        pool=str(args.pool),
        attn_dim=int(args.attn_dim),
        num_heads=int(args.num_heads),
        gat_layers=int(args.gat_layers),
        dropout=float(args.dropout),
    ).to(device)

    opt = torch.optim.AdamW(model.parameters(), lr=float(args.lr), weight_decay=float(args.weight_decay))

    scaler = torch.cuda.amp.GradScaler(enabled=bool(args.amp) and device.type == "cuda")

    scheduler = None
    if bool(args.lr_plateau):
        scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
            opt,
            mode="min",
            factor=float(args.lr_plateau_factor),
            patience=int(args.lr_plateau_patience),
            min_lr=float(args.min_lr),
            verbose=False,
        )

    best_val_ade = float("inf")
    best_val_fde = float("inf")
    best_epoch = -1
    best_val_top1_ade = float("inf")
    best_val_top1_fde = float("inf")
    best_top1_epoch = -1
    patience_left = int(args.patience)

    for epoch in range(1, int(args.epochs) + 1):
        model.train()
        train_losses = []
        for batch in train_loader:
            batch_t = Batch(
                obs_abs=batch.obs_abs.to(device),
                pred_abs=batch.pred_abs.to(device),
                obs_rel=batch.obs_rel.to(device),
                pred_rel=batch.pred_rel.to(device),
                agent_mask=batch.agent_mask.to(device),
            )
            opt.zero_grad(set_to_none=True)
            with torch.cuda.amp.autocast(enabled=scaler.is_enabled()):
                pred_rel_k, mode_logits = model(batch_t.obs_rel, batch_t.agent_mask)
                reg_loss, best_mode = variety_loss_mse_and_best_mode(pred_rel_k, batch_t.pred_rel, batch_t.agent_mask)

                if float(args.mode_cls_weight) > 0.0:
                    valid = batch_t.agent_mask
                    if bool(valid.any()):
                        ce = F.cross_entropy(mode_logits[valid], best_mode[valid])
                    else:
                        ce = torch.zeros((), device=device)
                    loss = reg_loss + float(args.mode_cls_weight) * ce
                else:
                    loss = reg_loss

            scaler.scale(loss).backward()
            scaler.unscale_(opt)
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            scaler.step(opt)
            scaler.update()
            train_losses.append(float(loss.item()))

        # Val
        model.eval()
        val_ades = []
        val_fdes = []
        val_top1_ades = []
        val_top1_fdes = []
        for batch in val_loader:
            batch_t = Batch(
                obs_abs=batch.obs_abs.to(device),
                pred_abs=batch.pred_abs.to(device),
                obs_rel=batch.obs_rel.to(device),
                pred_rel=batch.pred_rel.to(device),
                agent_mask=batch.agent_mask.to(device),
            )
            pred_rel_k, mode_logits = model(batch_t.obs_rel, batch_t.agent_mask)
            ade, fde = bestofk_ade_fde(batch_t.obs_abs, batch_t.pred_abs, pred_rel_k, batch_t.agent_mask)
            if str(args.top1_by) == "argmax":
                top1_ade, top1_fde = top1_by_logits_ade_fde(
                    batch_t.obs_abs,
                    batch_t.pred_abs,
                    pred_rel_k,
                    mode_logits,
                    batch_t.agent_mask,
                )
            else:
                top1_ade, top1_fde = top1_ade_fde(
                    batch_t.obs_abs,
                    batch_t.pred_abs,
                    pred_rel_k,
                    batch_t.agent_mask,
                    mode_index=int(args.top1_mode_index),
                )
            val_ades.append(ade)
            val_fdes.append(fde)
            val_top1_ades.append(top1_ade)
            val_top1_fdes.append(top1_fde)

        val_ade = float(np.nanmean(val_ades))
        val_fde = float(np.nanmean(val_fdes))
        val_top1_ade = float(np.nanmean(val_top1_ades))
        val_top1_fde = float(np.nanmean(val_top1_fdes))
        train_loss = float(np.mean(train_losses))

        if scheduler is not None:
            scheduler.step(val_ade)

        lr_now = float(opt.param_groups[0]["lr"])

        improved = val_ade < best_val_ade - 1e-6
        if improved:
            best_val_ade = val_ade
            best_val_fde = val_fde
            best_epoch = epoch
            patience_left = int(args.patience)
            ckpt_path = Path(args.save_ckpt)
            ckpt_path.parent.mkdir(parents=True, exist_ok=True)
            torch.save(
                {
                    "model": model.state_dict(),
                    "epoch": epoch,
                    "val_ade": val_ade,
                    "val_fde": val_fde,
                    "args": vars(args),
                },
                ckpt_path,
            )
        elif int(args.patience) > 0:
            patience_left -= 1

        if val_top1_ade < best_val_top1_ade - 1e-6:
            best_val_top1_ade = val_top1_ade
            best_val_top1_fde = val_top1_fde
            best_top1_epoch = epoch

        log_every = int(args.log_every)
        if log_every <= 0:
            log_every = 1

        if epoch == 1 or epoch % log_every == 0 or improved:
            print(
                f"epoch {epoch:3d} | lr={lr_now:.2e} | train_loss={train_loss:.6f} | val_bestK_ADE={val_ade:.4f} | val_bestK_FDE={val_fde:.4f} | val_top1_ADE={val_top1_ade:.4f} | val_top1_FDE={val_top1_fde:.4f}"
                + ("  (best)" if improved else "")
            )

        if int(args.patience) > 0 and patience_left <= 0:
            print(f"early stopping at epoch {epoch} (best_epoch={best_epoch}, best_val_ADE={best_val_ade:.4f})")
            break

    # Reload best
    ckpt = torch.load(Path(args.save_ckpt), map_location=device)
    model.load_state_dict(ckpt["model"])

    # Save final val best-mode predictions
    model.eval()
    with torch.no_grad():
        global_max_m = 0
        for batch in val_loader:
            global_max_m = max(global_max_m, int(batch.agent_mask.shape[1]))

        all_pred_abs: List[torch.Tensor] = []
        all_pred_abs_top1: List[torch.Tensor] = []
        all_gt_abs: List[torch.Tensor] = []
        all_masks: List[torch.Tensor] = []
        all_best_k: List[torch.Tensor] = []
        all_top1_k: List[torch.Tensor] = []

        for batch in val_loader:
            batch_t = Batch(
                obs_abs=batch.obs_abs.to(device),
                pred_abs=batch.pred_abs.to(device),
                obs_rel=batch.obs_rel.to(device),
                pred_rel=batch.pred_rel.to(device),
                agent_mask=batch.agent_mask.to(device),
            )
            pred_rel_k, mode_logits = model(batch_t.obs_rel, batch_t.agent_mask)
            pred_abs_best, best_k = best_mode_prediction(batch_t.obs_abs, batch_t.pred_abs, pred_rel_k, batch_t.agent_mask)
            if str(args.top1_by) == "argmax":
                pred_abs_top1, top1_k = top1_by_logits_prediction(batch_t.obs_abs, pred_rel_k, mode_logits)
            else:
                pred_abs_top1 = top1_prediction(batch_t.obs_abs, pred_rel_k, mode_index=int(args.top1_mode_index))
                top1_k = torch.full_like(best_k, int(args.top1_mode_index))

            B, m_batch, _, Tpred = pred_abs_best.shape
            if m_batch < global_max_m:
                pad_pred = torch.zeros((B, global_max_m, 2, Tpred), dtype=pred_abs_best.dtype, device=pred_abs_best.device)
                pad_pred_top1 = torch.zeros((B, global_max_m, 2, Tpred), dtype=pred_abs_top1.dtype, device=pred_abs_top1.device)
                pad_gt = torch.zeros((B, global_max_m, 2, Tpred), dtype=batch_t.pred_abs.dtype, device=batch_t.pred_abs.device)
                pad_mask = torch.zeros((B, global_max_m), dtype=batch_t.agent_mask.dtype, device=batch_t.agent_mask.device)
                pad_k = torch.full((B, global_max_m), -1, dtype=torch.int64, device=best_k.device)
                pad_top1_k = torch.full((B, global_max_m), -1, dtype=torch.int64, device=best_k.device)

                pad_pred[:, :m_batch] = pred_abs_best
                pad_pred_top1[:, :m_batch] = pred_abs_top1
                pad_gt[:, :m_batch] = batch_t.pred_abs
                pad_mask[:, :m_batch] = batch_t.agent_mask
                pad_k[:, :m_batch] = best_k
                pad_top1_k[:, :m_batch] = top1_k

                pred_abs_best = pad_pred
                pred_abs_top1 = pad_pred_top1
                pred_abs_gt = pad_gt
                mask = pad_mask
                best_k = pad_k
                top1_k = pad_top1_k
            else:
                pred_abs_gt = batch_t.pred_abs
                mask = batch_t.agent_mask

            all_pred_abs.append(pred_abs_best.detach().cpu())
            all_pred_abs_top1.append(pred_abs_top1.detach().cpu())
            all_gt_abs.append(pred_abs_gt.detach().cpu())
            all_masks.append(mask.detach().cpu())
            all_best_k.append(best_k.detach().cpu())
            all_top1_k.append(top1_k.detach().cpu())

    pred_abs_hat = torch.cat(all_pred_abs, dim=0).numpy()
    pred_abs_top1 = torch.cat(all_pred_abs_top1, dim=0).numpy()
    gt_abs = torch.cat(all_gt_abs, dim=0).numpy()
    masks = torch.cat(all_masks, dim=0).numpy()
    best_k = torch.cat(all_best_k, dim=0).numpy()
    top1_k = torch.cat(all_top1_k, dim=0).numpy()

    metrics = {
        "model": "MFP_bestofK",
        "data": str(data_path).replace("\\", "/"),
        "obs_len": int(obs_len),
        "pred_len": int(pred_len),
        "split": train_ds.split_kind,
        "seed": int(args.seed),
        "val_frac": float(args.val_frac),
        "train_seqs": int(len(train_ds)),
        "val_seqs": int(len(val_ds)),
        "best_epoch": int(best_epoch),
        "best_val_ade": float(best_val_ade),
        "best_val_fde": float(best_val_fde),
        "best_top1_epoch": int(best_top1_epoch),
        "best_val_top1_ade": float(best_val_top1_ade),
        "best_val_top1_fde": float(best_val_top1_fde),
        "device": str(device),
        "hyper": {
            "k": int(args.k),
            "emb_dim": int(args.emb_dim),
            "hidden_dim": int(args.hidden_dim),
            "pool": str(args.pool),
            "attn_dim": int(args.attn_dim),
            "num_heads": int(args.num_heads),
            "gat_layers": int(args.gat_layers),
            "dropout": float(args.dropout),
            "batch_size": int(args.batch_size),
            "epochs": int(args.epochs),
            "log_every": int(args.log_every),
            "lr": float(args.lr),
            "weight_decay": float(args.weight_decay),
            "patience": int(args.patience),
            "lr_plateau": bool(args.lr_plateau),
            "amp": bool(args.amp) and device.type == "cuda",
            "mode_cls_weight": float(args.mode_cls_weight),
            "top1_by": str(args.top1_by),
            "top1_mode_index": int(args.top1_mode_index),
        },
        "when": datetime.now().isoformat(timespec="seconds"),
        "note": "MFP baseline: predict K futures; train with best-of-K (variety) loss. Also learns a mode scoring head (CE to oracle-best mode) so top-1 can be chosen via argmax(logits).",
    }

    Path(args.save_metrics_json).parent.mkdir(parents=True, exist_ok=True)
    with open(args.save_metrics_json, "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2)

    np.savez_compressed(
        args.save_pred_npz,
        pred_abs_best=pred_abs_hat.astype(np.float32),
        pred_abs_top1=pred_abs_top1.astype(np.float32),
        gt_abs=gt_abs.astype(np.float32),
        mask=masks.astype(bool),
        best_k=best_k.astype(np.int64),
        top1_k=top1_k.astype(np.int64),
    )

    print(f"saved metrics: {args.save_metrics_json}")
    print(f"saved ckpt:    {args.save_ckpt}")
    print(f"saved preds:   {args.save_pred_npz}")
    return 0


