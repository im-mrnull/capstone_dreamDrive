def set_seed(seed: int) -> None:
    torch.manual_seed(seed)
    np.random.seed(seed)


@dataclass
class Batch:
    obs_abs: torch.Tensor  # (B, M, 2, obs_len)
    pred_abs: torch.Tensor  # (B, M, 2, pred_len)
    obs_rel: torch.Tensor  # (B, M, 2, obs_len)
    pred_rel: torch.Tensor  # (B, M, 2, pred_len)
    agent_mask: torch.Tensor  # (B, M) bool


class STGATSeqDataset(Dataset):
    def __init__(
        self,
        npz_path: Path,
        split: str,
        val_frac: float,
        seed: int,
        split_by_scene: bool = True,
    ) -> None:
        super().__init__()
        data = np.load(npz_path, allow_pickle=True)
        self.obs_traj = data["obs_traj"].astype(np.float32)  # (N, 2, obs)
        self.pred_traj = data["pred_traj"].astype(np.float32)  # (N, 2, pred)
        self.obs_traj_rel = data["obs_traj_rel"].astype(np.float32)  # (N, 2, obs)
        self.pred_traj_rel = data["pred_traj_rel"].astype(np.float32)  # (N, 2, pred)
        self.seq_start_end = data["seq_start_end"].astype(np.int64)  # (S, 2)
        self.scene_id = data["scene_id"].astype(object) if "scene_id" in data else None

        self.num_seqs = int(self.seq_start_end.shape[0])
        if self.scene_id is None or not split_by_scene:
            rng = np.random.default_rng(seed)
            idx = np.arange(self.num_seqs)
            rng.shuffle(idx)
            n_val = max(1, int(round(self.num_seqs * float(val_frac))))
            val_set = set(idx[:n_val].tolist())
            keep = [i for i in range(self.num_seqs) if (i in val_set) == (split == "val")]
            self.seq_indices = np.asarray(keep, dtype=np.int64)
            self.split_kind = "random"
        else:
            rng = np.random.default_rng(seed)
            unique_scenes = np.unique(self.scene_id)
            rng.shuffle(unique_scenes)
            n_val = max(1, int(round(len(unique_scenes) * float(val_frac))))
            val_scenes = set(unique_scenes[:n_val].tolist())
            keep = []
            for i in range(self.num_seqs):
                sid = self.scene_id[i]
                is_val = sid in val_scenes
                if (split == "val" and is_val) or (split == "train" and not is_val):
                    keep.append(i)
            self.seq_indices = np.asarray(keep, dtype=np.int64)
            self.split_kind = "scene"

    def __len__(self) -> int:
        return int(self.seq_indices.shape[0])

    def __getitem__(self, idx: int) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
        seq_i = int(self.seq_indices[idx])
        s, e = self.seq_start_end[seq_i]
        obs = self.obs_traj[s:e]  # (M, 2, obs)
        pred = self.pred_traj[s:e]  # (M, 2, pred)
        obs_rel = self.obs_traj_rel[s:e]  # (M, 2, obs)
        pred_rel = self.pred_traj_rel[s:e]  # (M, 2, pred)
        return obs, pred, obs_rel, pred_rel


def collate_pad(batch_items: List[Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]]) -> Batch:
    B = len(batch_items)
    obs_len = batch_items[0][0].shape[-1]
    pred_len = batch_items[0][1].shape[-1]
    max_m = max(item[0].shape[0] for item in batch_items)

    obs_abs = torch.zeros((B, max_m, 2, obs_len), dtype=torch.float32)
    pred_abs = torch.zeros((B, max_m, 2, pred_len), dtype=torch.float32)
    obs_rel = torch.zeros((B, max_m, 2, obs_len), dtype=torch.float32)
    pred_rel = torch.zeros((B, max_m, 2, pred_len), dtype=torch.float32)
    agent_mask = torch.zeros((B, max_m), dtype=torch.bool)

    for b, (o, p, orl, prl) in enumerate(batch_items):
        m = o.shape[0]
        obs_abs[b, :m] = torch.from_numpy(o)
        pred_abs[b, :m] = torch.from_numpy(p)
        obs_rel[b, :m] = torch.from_numpy(orl)
        pred_rel[b, :m] = torch.from_numpy(prl)
        agent_mask[b, :m] = True

    return Batch(obs_abs=obs_abs, pred_abs=pred_abs, obs_rel=obs_rel, pred_rel=pred_rel, agent_mask=agent_mask)


class AgentSelfAttentionLayer(nn.Module):
    def __init__(self, hidden_dim: int, num_heads: int, dropout: float) -> None:
        super().__init__()
        self.mha = nn.MultiheadAttention(
            embed_dim=hidden_dim,
            num_heads=num_heads,
            dropout=dropout,
            batch_first=True,
        )
        self.ln1 = nn.LayerNorm(hidden_dim)
        self.ff = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim * 4),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim * 4, hidden_dim),
        )
        self.ln2 = nn.LayerNorm(hidden_dim)
        self.drop = nn.Dropout(dropout)

    def forward(self, h: torch.Tensor, agent_mask: torch.Tensor) -> torch.Tensor:
        key_padding_mask = ~agent_mask
        attn_out, _ = self.mha(h, h, h, key_padding_mask=key_padding_mask, need_weights=False)
        h = self.ln1(h + self.drop(attn_out))
        h2 = self.ff(h)
        h = self.ln2(h + self.drop(h2))
        return h


class GraphAttentionPool(nn.Module):
    def __init__(self, hidden_dim: int, attn_dim: int) -> None:
        super().__init__()
        self.q = nn.Linear(hidden_dim, attn_dim)
        self.k = nn.Linear(hidden_dim, attn_dim)
        self.v = nn.Linear(hidden_dim, attn_dim)
        self.out = nn.Linear(hidden_dim + attn_dim, hidden_dim)

    def forward(self, h: torch.Tensor, mask: torch.Tensor) -> torch.Tensor:
        B, M, _ = h.shape
        q = self.q(h)
        k = self.k(h)
        v = self.v(h)

        scale = 1.0 / math.sqrt(k.shape[-1])
        scores = torch.matmul(q, k.transpose(1, 2)) * scale  # (B,M,M)

        key_mask = mask.unsqueeze(1).expand(B, M, M)
        neg_inf = torch.finfo(scores.dtype).min
        scores = scores.masked_fill(~key_mask, neg_inf)

        query_mask = mask.unsqueeze(2).expand(B, M, M)
        scores = scores.masked_fill(~query_mask, 0.0)

        attn = torch.softmax(scores, dim=-1)
        attn = attn * query_mask.float()

        ctx = torch.matmul(attn, v)
        fused = torch.cat([h, ctx], dim=-1)
        return torch.tanh(self.out(fused))


class MFPModel(nn.Module):
    def __init__(
        self,
        obs_len: int,
        pred_len: int,
        k: int,
        emb_dim: int = 64,
        hidden_dim: int = 256,
        pool: str = "mha",
        attn_dim: int = 128,
        num_heads: int = 4,
        gat_layers: int = 2,
        dropout: float = 0.1,
        mode_emb_dim: int | None = None,
    ) -> None:
        super().__init__()
        self.obs_len = int(obs_len)
        self.pred_len = int(pred_len)
        self.k = int(k)

        self.emb = nn.Linear(2, emb_dim)
        self.encoder = nn.LSTM(
            input_size=emb_dim,
            hidden_size=hidden_dim,
            num_layers=1,
            batch_first=True,
            dropout=0.0,
        )

        self.pool_type = str(pool)
        if self.pool_type not in {"none", "simple", "mha"}:
            raise ValueError("pool must be one of: none, simple, mha")

        self.simple_pool = GraphAttentionPool(hidden_dim=hidden_dim, attn_dim=attn_dim)

        if hidden_dim % num_heads != 0:
            raise ValueError(f"hidden_dim ({hidden_dim}) must be divisible by num_heads ({num_heads})")

        self.mha_layers = nn.ModuleList(
            [AgentSelfAttentionLayer(hidden_dim=hidden_dim, num_heads=num_heads, dropout=dropout) for _ in range(gat_layers)]
        )

        # Mode embedding to encourage diverse futures.
        if mode_emb_dim is None:
            mode_emb_dim = emb_dim
        self.mode_emb = nn.Embedding(self.k, mode_emb_dim)

        self.dec_in = nn.Linear(2, emb_dim)
        self.mode_to_emb = nn.Linear(mode_emb_dim, emb_dim, bias=False)
        self.decoder_cell = nn.LSTMCell(input_size=emb_dim, hidden_size=hidden_dim)
        self.out = nn.Linear(hidden_dim, 2)

        self.init_h = nn.Linear(hidden_dim, self.k * hidden_dim)
        self.init_c = nn.Linear(hidden_dim, self.k * hidden_dim)

        # Learns a per-mode score so we can select a meaningful "top-1" mode at inference.
        self.mode_score = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim),
            nn.ReLU(inplace=True),
            nn.Linear(hidden_dim, 1),
        )

        self.drop = nn.Dropout(dropout)

    def forward(self, obs_rel: torch.Tensor, agent_mask: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        # obs_rel: (B,M,2,obs)
        B, M, _, obs_len = obs_rel.shape
        assert obs_len == self.obs_len

        # Encode per agent
        x = obs_rel.permute(0, 1, 3, 2).contiguous().view(B * M, obs_len, 2)
        x = self.drop(torch.relu(self.emb(x)))
        _, (h_n, _) = self.encoder(x)
        h_last = h_n[-1].view(B, M, -1)  # (B,M,H)

        # Interaction
        if self.pool_type == "none":
            h_ctx = h_last
        elif self.pool_type == "simple":
            h_ctx = self.simple_pool(h_last, agent_mask)
        else:
            h_ctx = h_last
            for layer in self.mha_layers:
                h_ctx = layer(h_ctx, agent_mask)

        # Initialize per-mode decoder states from context
        h0 = self.init_h(h_ctx).view(B, M, self.k, -1)  # (B,M,K,H)
        c0 = self.init_c(h_ctx).view(B, M, self.k, -1)

        # (B,M,K) logits; training will apply CE to teach correct mode selection.
        mode_logits = self.mode_score(h0).squeeze(-1)

        # Flatten modes into batch
        h = h0.reshape(B * M * self.k, -1)
        c = c0.reshape(B * M * self.k, -1)

        # Mode embedding
        mode_ids = torch.arange(self.k, device=obs_rel.device).view(1, 1, self.k).expand(B, M, self.k)
        mode_e = self.mode_to_emb(self.mode_emb(mode_ids)).reshape(B * M * self.k, -1)  # (B*M*K, emb)

        prev_rel = obs_rel[:, :, :, -1].permute(0, 1, 2).contiguous()  # (B,M,2)
        prev_rel = prev_rel.unsqueeze(2).expand(B, M, self.k, 2).reshape(B * M * self.k, 2)

        preds: List[torch.Tensor] = []
        for _t in range(self.pred_len):
            inp = self.drop(torch.relu(self.dec_in(prev_rel) + mode_e))
            h, c = self.decoder_cell(inp, (h, c))
            step = self.out(self.drop(h))  # (B*M*K, 2)
            preds.append(step.view(B, M, self.k, 2))
            prev_rel = step

        pred_rel_hat = torch.stack(preds, dim=-1)  # (B,M,K,2,T)
        return pred_rel_hat, mode_logits


def variety_loss_mse_and_best_mode(
    pred_rel_k: torch.Tensor,  # (B,M,K,2,T)
    gt_rel: torch.Tensor,  # (B,M,2,T)
    agent_mask: torch.Tensor,  # (B,M)
) -> Tuple[torch.Tensor, torch.Tensor]:
    diff = pred_rel_k - gt_rel.unsqueeze(2)
    per_mode = (diff * diff).sum(dim=(3, 4))  # (B,M,K)

    valid = agent_mask.unsqueeze(2).float()
    per_mode = per_mode + (1.0 - valid) * 1e9

    best_mode = per_mode.argmin(dim=2)  # (B,M)

    best = pred_rel_k.gather(2, best_mode.unsqueeze(-1).unsqueeze(-1).unsqueeze(-1).expand(-1, -1, 1, 2, gt_rel.shape[-1]))
    best = best.squeeze(2)  # (B,M,2,T)

    m = agent_mask.unsqueeze(2).unsqueeze(3).float()
    diff_best = (best - gt_rel) * m
    loss = (diff_best * diff_best).sum() / (m.sum().clamp_min(1.0) * 2.0 * gt_rel.shape[-1])
    return loss, best_mode


def variety_loss_mse(
    pred_rel_k: torch.Tensor,  # (B,M,K,2,T)
    gt_rel: torch.Tensor,  # (B,M,2,T)
    agent_mask: torch.Tensor,  # (B,M)
) -> torch.Tensor:
    loss, _best_mode = variety_loss_mse_and_best_mode(pred_rel_k, gt_rel, agent_mask)
    return loss


@torch.no_grad()
def top1_by_logits_ade_fde(
    obs_abs: torch.Tensor,  # (B,M,2,obs)
    pred_abs_gt: torch.Tensor,  # (B,M,2,pred)
    pred_rel_k: torch.Tensor,  # (B,M,K,2,pred)
    mode_logits: torch.Tensor,  # (B,M,K)
    agent_mask: torch.Tensor,  # (B,M)
) -> Tuple[float, float]:
    top1_k = mode_logits.argmax(dim=-1)  # (B,M)
    pred_rel = pred_rel_k.gather(
        2,
        top1_k.unsqueeze(-1).unsqueeze(-1).unsqueeze(-1).expand(-1, -1, 1, 2, pred_rel_k.shape[-1]),
    ).squeeze(2)  # (B,M,2,T)

    start = obs_abs[:, :, :, -1]
    pred_abs_hat = start.unsqueeze(-1) + torch.cumsum(pred_rel, dim=-1)

    err = torch.linalg.vector_norm((pred_abs_hat - pred_abs_gt).permute(0, 1, 3, 2), dim=-1)  # (B,M,T)
    m = agent_mask.float()
    denom = m.sum().clamp_min(1.0)
    ade = (err * m.unsqueeze(-1)).sum() / (denom * err.shape[-1])
    fde = (err[:, :, -1] * m).sum() / denom
    return float(ade.item()), float(fde.item())


@torch.no_grad()
def bestofk_ade_fde(
    obs_abs: torch.Tensor,  # (B,M,2,obs)
    pred_abs_gt: torch.Tensor,  # (B,M,2,pred)
    pred_rel_k: torch.Tensor,  # (B,M,K,2,pred)
    agent_mask: torch.Tensor,  # (B,M)
) -> Tuple[float, float]:
    start = obs_abs[:, :, :, -1]  # (B,M,2)
    pred_abs_k = start.unsqueeze(2).unsqueeze(-1) + torch.cumsum(pred_rel_k, dim=-1)  # (B,M,K,2,T)

    # (B,M,K,T)
    err = torch.linalg.vector_norm(
        (pred_abs_k - pred_abs_gt.unsqueeze(2)).permute(0, 1, 2, 4, 3),
        dim=-1,
    )

    ade_k = err.mean(dim=-1)  # (B,M,K)
    fde_k = err[:, :, :, -1]  # (B,M,K)

    valid = agent_mask.unsqueeze(2).float()
    ade_k = ade_k + (1.0 - valid) * 1e9
    fde_k = fde_k + (1.0 - valid) * 1e9

    ade_best = ade_k.min(dim=2).values  # (B,M)
    fde_best = fde_k.min(dim=2).values

    denom = agent_mask.float().sum().clamp_min(1.0)
    ade = (ade_best * agent_mask.float()).sum() / denom
    fde = (fde_best * agent_mask.float()).sum() / denom
    return float(ade.item()), float(fde.item())


@torch.no_grad()
def top1_ade_fde(
    obs_abs: torch.Tensor,  # (B,M,2,obs)
    pred_abs_gt: torch.Tensor,  # (B,M,2,pred)
    pred_rel_k: torch.Tensor,  # (B,M,K,2,pred)
    agent_mask: torch.Tensor,  # (B,M)
    mode_index: int = 0,
) -> Tuple[float, float]:
    """Compute single-trajectory (top-1) ADE/FDE.

    This legacy helper defines "top-1" as a fixed deterministic mode (default: mode 0).
    Prefer `top1_by_logits_ade_fde` which selects the most-likely mode using learned logits.
    """
    k = int(pred_rel_k.shape[2])
    if not (0 <= mode_index < k):
        raise ValueError(f"mode_index out of range: {mode_index} for K={k}")

    pred_rel = pred_rel_k[:, :, mode_index]  # (B,M,2,T)
    start = obs_abs[:, :, :, -1]
    pred_abs_hat = start.unsqueeze(-1) + torch.cumsum(pred_rel, dim=-1)

    err = torch.linalg.vector_norm((pred_abs_hat - pred_abs_gt).permute(0, 1, 3, 2), dim=-1)  # (B,M,T)
    m = agent_mask.float()
    denom = m.sum().clamp_min(1.0)
    ade = (err * m.unsqueeze(-1)).sum() / (denom * err.shape[-1])
    fde = (err[:, :, -1] * m).sum() / denom
    return float(ade.item()), float(fde.item())


@torch.no_grad()
def best_mode_prediction(
    obs_abs: torch.Tensor,
    pred_abs_gt: torch.Tensor,
    pred_rel_k: torch.Tensor,
    agent_mask: torch.Tensor,
) -> Tuple[torch.Tensor, torch.Tensor]:
    start = obs_abs[:, :, :, -1]
    pred_abs_k = start.unsqueeze(2).unsqueeze(-1) + torch.cumsum(pred_rel_k, dim=-1)  # (B,M,K,2,T)

    err = torch.linalg.vector_norm(
        (pred_abs_k - pred_abs_gt.unsqueeze(2)).permute(0, 1, 2, 4, 3),
        dim=-1,
    )
    ade_k = err.mean(dim=-1)  # (B,M,K)
    ade_k = ade_k + (~agent_mask).unsqueeze(2).float() * 1e9
    best_k = ade_k.argmin(dim=2)  # (B,M)

    best_pred = pred_abs_k.gather(
        2,
        best_k.unsqueeze(-1).unsqueeze(-1).unsqueeze(-1).expand(-1, -1, 1, 2, pred_abs_k.shape[-1]),
    ).squeeze(2)

    return best_pred, best_k


@torch.no_grad()
def top1_prediction(
    obs_abs: torch.Tensor,
    pred_rel_k: torch.Tensor,
    mode_index: int = 0,
) -> torch.Tensor:
    start = obs_abs[:, :, :, -1]
    pred_rel = pred_rel_k[:, :, mode_index]  # (B,M,2,T)
    pred_abs = start.unsqueeze(-1) + torch.cumsum(pred_rel, dim=-1)
    return pred_abs


@torch.no_grad()
def top1_by_logits_prediction(
    obs_abs: torch.Tensor,
    pred_rel_k: torch.Tensor,
    mode_logits: torch.Tensor,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """Return top-1 absolute prediction chosen by argmax(logits) plus chosen mode index.

    Returns:
        pred_abs: (B,M,2,T)
        top1_k:   (B,M)
    """
    top1_k = mode_logits.argmax(dim=-1)  # (B,M)
    pred_rel = pred_rel_k.gather(
        2,
        top1_k.unsqueeze(-1).unsqueeze(-1).unsqueeze(-1).expand(-1, -1, 1, 2, pred_rel_k.shape[-1]),
    ).squeeze(2)  # (B,M,2,T)

    start = obs_abs[:, :, :, -1]
    pred_abs = start.unsqueeze(-1) + torch.cumsum(pred_rel, dim=-1)
    return pred_abs, top1_k


